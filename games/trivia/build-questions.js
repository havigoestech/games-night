#!/usr/bin/env node
/*
 * build-questions.js — harvests the Open Trivia DB into a bundled data file.
 *
 *   node games/trivia/build-questions.js
 *
 * Open Trivia DB (https://opentdb.com) data is licensed CC BY-SA 4.0.
 * We snapshot it once into games/trivia/data/questions-mc.js so the game has
 * no runtime dependency on the API. Re-run any time to refresh.
 *
 * The API allows one request per IP every ~5s and 50 questions per call, one
 * category per call, and uses a session token so we don't get repeats.
 */
const fs = require('fs');
const path = require('path');

const PACE_MS = 5500;        // stay under the 1-request-per-5s limit
const PER_CALL = 50;
const MAX_CALLS_PER_CAT = 40; // safety ceiling (~2000 Qs/cat — far more than exist)
const sleep = ms => new Promise(r => setTimeout(r, ms));
const b64 = s => Buffer.from(String(s), 'base64').toString('utf8');

// Child-safe-biased clean flag (OpenTDB is mostly clean; flag the rare adult one).
const RUDE = new RegExp('\\b(' + [
  'sex','sexual','sexy','naked','nude','porn','penis','vagina','orgasm','condom',
  'masturbat','erotic','breast','nipple','genital','prostitut','brothel','incest',
  'rape','bdsm','fetish','drunk','heroin','cocaine','meth','damn','hell','ass',
  'bitch','bastard','whore','slut','fuck','shit','piss','cunt','dick','cock',
].join('|') + ')\\b', 'i');

async function getJSON(url, tries = 5) {
  for (let i = 0; i < tries; i++) {
    const ctrl = new AbortController();
    const t = setTimeout(() => ctrl.abort(), 20000);
    try {
      const res = await fetch(url, { signal: ctrl.signal });
      clearTimeout(t);
      if (res.status === 429) { await sleep(PACE_MS * (i + 2)); continue; }
      if (!res.ok) throw new Error('HTTP ' + res.status);
      return await res.json();
    } catch (e) { clearTimeout(t); if (i === tries - 1) throw e; await sleep(PACE_MS); }
  }
}

(async () => {
  const cats = (await getJSON('https://opentdb.com/api_category.php')).trivia_categories;
  console.log(`categories: ${cats.length}`);
  let token = (await getJSON('https://opentdb.com/api_token.php?command=request')).token;
  console.log('got session token');

  const byKey = new Map();
  const norm = s => s.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
  let total = 0;

  for (const cat of cats) {
    let got = 0;
    for (let call = 0; call < MAX_CALLS_PER_CAT; call++) {
      await sleep(PACE_MS);
      const url = `https://opentdb.com/api.php?amount=${PER_CALL}&category=${cat.id}&type=multiple&encode=base64&token=${token}`;
      let j;
      try { j = await getJSON(url); } catch (e) { console.log(`  ${cat.name}: fetch error (${e.message}), skipping rest`); break; }
      const code = j.response_code;
      if (code === 3 || code === 4) {               // token empty/expired for this query
        if (code === 3) { token = (await getJSON('https://opentdb.com/api_token.php?command=request')).token; continue; }
        break;                                       // code 4: exhausted this category
      }
      if (code === 1 || !j.results || !j.results.length) break; // no (more) results
      if (code !== 0) { console.log(`  ${cat.name}: response_code ${code}, stopping`); break; }

      for (const r of j.results) {
        const q = b64(r.question).trim();
        const correct = b64(r.correct_answer).trim();
        let wrong = (r.incorrect_answers || []).map(b64).map(s => s.trim()).filter(Boolean);
        // Drop wrongs that duplicate each other or the correct answer, comparing
        // on the normalised form (so "USA" vs "U.S.A." counts as a dup). OpenTDB
        // occasionally ships these, which would render near-identical options.
        const seenW = new Set([norm(correct)]);
        wrong = wrong.filter(w => { const k = norm(w); if (!k || seenW.has(k)) return false; seenW.add(k); return true; });
        if (!q || !correct || wrong.length < 3) continue;
        const key = norm(q);
        if (byKey.has(key)) continue;
        const catName = b64(r.category).replace(/^Entertainment: |^Science: /, '').trim();
        const blob = q + ' ' + correct + ' ' + wrong.join(' ');
        byKey.set(key, { q, correct, wrong: wrong.slice(0, 3), cat: catName, diff: b64(r.difficulty), clean: !RUDE.test(blob) });
        got++;
      }
    }
    total = byKey.size;
    console.log(`  ${cat.name}: +${got}  (running total ${total})`);
  }

  const all = [...byKey.values()];
  const clean = all.filter(q => q.clean).length;
  const header =
    '// AUTO-GENERATED by games/trivia/build-questions.js — do not edit by hand.\n' +
    '// Source: Open Trivia Database (https://opentdb.com), licensed CC BY-SA 4.0.\n' +
    '// Attribution required; questions redistributed under the same license.\n' +
    `// ${all.length} multiple-choice questions (${clean} clean). Regenerate: node games/trivia/build-questions.js\n` +
    '// Shape: { q, correct, wrong:[3], cat, diff, clean }\n' +
    'module.exports = { QUESTIONS: [\n';
  const body = all.map(q => '  ' + JSON.stringify(q)).join(',\n');
  fs.writeFileSync(path.join(__dirname, 'data', 'questions-mc.js'), header + body + '\n] };\n');

  // Category index for the host's picker.
  const catCounts = {};
  all.forEach(q => { catCounts[q.cat] = (catCounts[q.cat] || 0) + 1; });
  console.log(`\nTOTAL: ${all.length} questions (${clean} clean, ${all.length - clean} flagged)`);
  console.log('categories:', Object.keys(catCounts).length);
  console.log('wrote games/trivia/data/questions-mc.js');
})().catch(e => { console.error('HARVEST FAILED:', e); process.exit(1); });
